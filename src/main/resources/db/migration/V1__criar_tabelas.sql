CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(10) NOT NULL UNIQUE
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    department_id BIGINT NOT NULL REFERENCES departments(id)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    registration VARCHAR(40) NOT NULL UNIQUE,
    type VARCHAR(20) NOT NULL,
    department_id BIGINT REFERENCES departments(id),
    CONSTRAINT ck_user_type CHECK (type IN ('SOLICITANTE', 'TECNICO'))
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    location VARCHAR(255) NOT NULL,
    priority VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL,
    opening_date TIMESTAMP NOT NULL,
    closing_date TIMESTAMP,
    solution TEXT,
    requester_id BIGINT NOT NULL REFERENCES users(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    technician_id BIGINT REFERENCES users(id),
    CONSTRAINT ck_ticket_priority CHECK (priority IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_ticket_status CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO'))
);

CREATE TABLE interactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL,
    date_time TIMESTAMP NOT NULL,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    author_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE INDEX idx_categories_department ON categories(department_id);
CREATE INDEX idx_tickets_category ON tickets(category_id);
CREATE INDEX idx_tickets_requester ON tickets(requester_id);
CREATE INDEX idx_tickets_technician ON tickets(technician_id);
CREATE INDEX idx_tickets_status ON tickets(status);
